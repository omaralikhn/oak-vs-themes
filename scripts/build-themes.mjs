import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { PALETTES } from './palettes.mjs'

const THEMES_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'themes')

function main() {
  mkdirSync(THEMES_DIR, { recursive: true })
  for (const palette of PALETTES) {
    const theme = buildTheme(palette)
    writeFileSync(join(THEMES_DIR, `${palette.file}-color-theme.json`), `${JSON.stringify(theme, null, 2)}\n`)
  }
}

function buildTheme(p) {
  return {
    $schema: 'vscode://schemas/color-theme',
    name: p.name,
    type: 'dark',
    semanticHighlighting: true,
    colors: buildWorkbenchColors(p),
    tokenColors: buildTokenColors(p),
    semanticTokenColors: buildSemanticTokenColors(p),
  }
}

